def build_baseline_coverage() -> None:
    rows = list(csv.DictReader((TABLE_DIR / "table1_main_results.csv").open()))
    by_setting: dict[tuple[str, str], set[str]] = defaultdict(set)
    for row in rows:
        by_setting[(row["dataset"], row["distribution"])].add(row["method"])

    csv_rows = []
    tex_rows = []
    for key in sorted(by_setting):
        methods = by_setting[key]
        missing = [m for m in METHOD_ORDER if m not in methods]
        coverage = f"{len(methods & set(METHOD_ORDER))}/{len(METHOD_ORDER)}"
        csv_rows.append(
            {
                "dataset": key[0],
                "distribution": key[1],
                "coverage": coverage,
                "available_methods": ";".join(m for m in METHOD_ORDER if m in methods),
                "missing_methods": ";".join(missing) if missing else "none",
            }
        )
        tex_rows.append(
            f"{esc(setting_name(*key))} & {coverage} & {esc(', '.join(METHOD_LABEL[m] for m in METHOD_ORDER if m in methods))} & {esc(', '.join(METHOD_LABEL[m] for m in missing) if missing else 'none')} \\\\"
        )

    with (TABLE_DIR / "app_baseline_coverage.csv").open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(csv_rows[0]))
        writer.writeheader()
        writer.writerows(csv_rows)
    print(TABLE_DIR / "app_baseline_coverage.csv")

    write(
        TABLE_DIR / "app_baseline_coverage.tex",
        "\n".join(
            [
                r"\begin{table*}[t]",
                r"\centering",
                r"\scriptsize",
                r"\caption{Baseline coverage in the final accepted result ledger. Coverage counts the six displayed methods in Table~\ref{tab:main-results}.}",
                r"\label{tab:app-baseline-coverage-mapping}",
                r"\begin{tabular}{@{}p{0.16\textwidth}p{0.08\textwidth}p{0.50\textwidth}p{0.18\textwidth}@{}}",
                r"\toprule",
                r"Setting & Coverage & Available methods & Missing methods \\",
                r"\midrule",
                "\n".join(tex_rows),
                r"\bottomrule",
                r"\end{tabular}",
                r"\end{table*}",
                "",
            ]
        ),
    )


