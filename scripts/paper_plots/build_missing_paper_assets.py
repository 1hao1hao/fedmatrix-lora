def read_eval_curve(path: Path, metric: str):
    xs = {"round": [], "budget": [], "time": [], "metric": []}
    if not path.exists():
        return xs
    with path.open() as f:
        reader = csv.DictReader(f)
        for row in reader:
            try:
                y = float(row[metric])
                xs["round"].append(float(row["Round"]))
                xs["budget"].append(float(row["Cumulative_Budget"]))
                xs["time"].append(float(row["Cumulative_Time"]))
                xs["metric"].append(y)
            except Exception:
                continue
    return xs


def build_full_curves() -> None:
    rows = list(csv.DictReader((TABLE_DIR / "table1_main_results.csv").open()))
    rows = [r for r in rows if r["dataset"] != "samsum" and r["metric"] == "Accuracy"]
    grouped: dict[tuple[str, str], list[dict[str, str]]] = defaultdict(list)
    for row in rows:
        grouped[(row["dataset"], row["distribution"])].append(row)

    settings = sorted(grouped)
    for xkey, xlabel, stem in [
        ("round", "Round", "app_full_round_curves"),
        ("budget", "Cumulative budget", "app_full_budget_curves"),
        ("time", "Cumulative time (s)", "app_full_time_curves"),
    ]:
        ncols = 3
        nrows = (len(settings) + ncols - 1) // ncols
        fig, axes = plt.subplots(nrows, ncols, figsize=(14, 3.0 * nrows), squeeze=False)
        for ax in axes.ravel():
            ax.axis("off")
        for ax, key in zip(axes.ravel(), settings):
            ax.axis("on")
            vals = grouped[key]
            yvals = []
            for method in METHOD_ORDER:
                row = next((r for r in vals if r["method"] == method), None)
                if not row:
                    continue
                curve = read_eval_curve(ROOT / row["raw_result_path"], row["metric"])
                if not curve["metric"]:
                    continue
                ax.plot(curve[xkey], curve["metric"], label=METHOD_LABEL[method], linewidth=1.4)
                yvals.extend(curve["metric"])
            ax.set_title(setting_name(*key), fontsize=9)
            ax.set_xlabel(xlabel, fontsize=8)
            ax.set_ylabel("Accuracy", fontsize=8)
            ax.grid(True, alpha=0.25)
            if yvals:
                lo, hi = min(yvals), max(yvals)
                pad = max((hi - lo) * 0.12, 0.02)
                ax.set_ylim(max(0.0, lo - pad), min(1.0, hi + pad))
        handles, labels = axes[0][0].get_legend_handles_labels()
        if handles:
            fig.legend(handles, labels, loc="lower center", ncol=min(6, len(labels)), fontsize=9)
        fig.suptitle(f"Full classification {xlabel.lower()} curves from final accepted rows", y=0.995, fontsize=12)
        fig.tight_layout(rect=(0, 0.035, 1, 0.965))
        for ext in ["png", "pdf"]:
            out = FIG_DIR / f"{stem}.{ext}"
            fig.savefig(out, dpi=300)
            print(out)
        plt.close(fig)


def main() -> None:
    build_notation_table()
    build_candidate_rules_table()
    build_baseline_coverage()
    build_claim_boundary()
    build_full_curves()


if __name__ == "__main__":
    main()
