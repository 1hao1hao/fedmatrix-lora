def esc(s: str) -> str:
    return (
        s.replace("\\", "\\textbackslash{}")
        .replace("_", "\\_")
        .replace("&", "\\&")
        .replace("%", "\\%")
        .replace("#", "\\#")
    )


def setting_name(dataset: str, distribution: str) -> str:
    dataset_label = {
        "cifar100": "CIFAR100",
        "sst2": "SST-2",
        "qnli": "QNLI",
        "qqp": "QQP",
        "mnli": "MNLI",
        "samsum": "SAMSum",
    }.get(dataset, dataset)
    dist = distribution.replace("dirichlet:", "D").replace("length_skew:", "Len-").replace("iid", "IID")
    return f"{dataset_label} / {dist}"


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    print(path)


